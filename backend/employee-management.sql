alter table public.user_profiles
  add column if not exists is_active boolean not null default true,
  add column if not exists deleted_at timestamptz;

create index if not exists user_profiles_employee_status_idx
  on public.user_profiles (role, is_active, branch_id);

create table if not exists public.employee_audit_log (
  id bigint generated by default as identity primary key,
  actor_user_id uuid,
  target_user_id uuid,
  action text not null check (action in ('create','block','unblock','delete')),
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

-- The audit table is server-only. No client-side policies or grants are provided.
alter table public.employee_audit_log enable row level security;
revoke all on table public.employee_audit_log from public, anon, authenticated;
grant all on table public.employee_audit_log to service_role;

-- A disabled/archived account has no application role, so existing RLS policies
-- and guarded RPCs immediately stop granting access while history remains intact.
create or replace function public.current_app_role()
returns text
language sql
stable
security definer
set search_path to 'public'
as $function$
  select role
  from public.user_profiles
  where user_id = auth.uid()
    and must_change_password = false
    and is_active = true
    and deleted_at is null
  limit 1;
$function$;

-- Close older privileged RPC/trigger paths that previously checked only
-- must_change_password but did not check whether the profile was disabled.
do $$
declare v text;
begin
  v := pg_get_functiondef('bardahl_branches_private.actor_branch()'::regprocedure);
  v := replace(v, 'AND NOT must_change_password;', 'AND NOT must_change_password AND is_active AND deleted_at IS NULL;');
  execute v;

  v := pg_get_functiondef('bardahl_branches_private.queue_action(text,jsonb)'::regprocedure);
  v := replace(v, 'AND NOT must_change_password;', 'AND NOT must_change_password AND is_active AND deleted_at IS NULL;');
  execute v;

  v := pg_get_functiondef('bardahl_branches_private.guard_order()'::regprocedure);
  v := replace(v, 'AND NOT must_change_password;', 'AND NOT must_change_password AND is_active AND deleted_at IS NULL;');
  execute v;

  v := pg_get_functiondef('public.set_queue_branch(integer)'::regprocedure);
  v := replace(v, 'AND NOT must_change_password FOR UPDATE;', 'AND NOT must_change_password AND is_active AND deleted_at IS NULL FOR UPDATE;');
  execute v;

  v := pg_get_functiondef('public.complete_password_change()'::regprocedure);
  v := replace(v, 'AND NOT must_change_password)', 'AND NOT must_change_password AND is_active AND deleted_at IS NULL)');
  execute v;

  v := pg_get_functiondef('public.current_profile_name()'::regprocedure);
  v := replace(v, 'where user_id=auth.uid() limit 1;', 'where user_id=auth.uid() and is_active and deleted_at is null limit 1;');
  execute v;

  v := pg_get_functiondef('bardahl_branches_private.password_changed()'::regprocedure);
  v := replace(v, 'WHERE user_id=NEW.id AND must_change_password;', 'WHERE user_id=NEW.id AND must_change_password AND is_active AND deleted_at IS NULL;');
  execute v;
end $$;
